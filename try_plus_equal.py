# ============================================
# += 到底是什么 —— 6 个小实验
# 跑法：VS Code 里按 F5，然后看输出
# ============================================

# --- 实验 1：+= 就是"自己加上右边，再存回自己" ---
print("--- 实验 1 ---")
total = 0
for n in [3, 7, 1, 9]:
    total += n                    # 等价于 total = total + n
    print(f"  加 {n} 之后，total = {total}")
print("  最终 total =", total)


# --- 实验 2：两种写法结果完全一样 ---
print("--- 实验 2 ---")
a = 10
b = 10
a += 5                # 简写
b = b + 5             # 展开写
print(f"  a = {a}   b = {b}   两个都是 15，一模一样")


# --- 实验 3：+= 只是这一大家子里的一员 ---
print("--- 实验 3 ---")
x = 20
x -= 5      ; print("  20 -= 5   ->", x)     # 15
x *= 2      ; print("  15 *= 2   ->", x)     # 30
x //= 4     ; print("  30 //= 4  ->", x)     # 7  整除
x **= 2     ; print("  7  **= 2  ->", x)     # 49 平方
x %= 5      ; print("  49 %= 5   ->", x)     # 4  取余


# --- 实验 4：字符串也能加 ---
print("--- 实验 4 ---")
s = "第"
s += "1"
s += "课"
print("  拼出来:", s)


# --- 实验 5：列表上 += 和 append 不一样（重点）---
print("--- 实验 5 ---")
nums = [1, 2]
nums += [3, 4]           # += 一次加进去多个，等于 nums.extend([3, 4])
print("  nums += [3, 4]       ->", nums)

nums2 = [1, 2]
nums2.append([3, 4])     # append 把 [3, 4] 当成"一个元素"塞进去
print("  nums2.append([3, 4]) ->", nums2)


# --- 实验 6：左边必须已经存在 ---
print("--- 实验 6 ---")
count = 0                # 先定义
count += 1               # 才能自增
print("  count =", count)
print("  如果没写 count = 0 就 count += 1，Python 会报 NameError")
